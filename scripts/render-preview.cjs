// Optional artifact renderer. Install playwright-core and a Chromium browser.
const {chromium}=require('playwright-core');
const path=require('node:path');
const fs=require('node:fs');
const {pathToFileURL}=require('node:url');
(async()=>{
 const root=path.resolve(__dirname,'..');
 const out=path.join(root,'test-output');fs.mkdirSync(out,{recursive:true});
 const browser=await chromium.launch({headless:true,...(process.env.BORALANCES_CHROMIUM?{executablePath:process.env.BORALANCES_CHROMIUM}:{channel:'msedge'})});
 const page=await browser.newPage({viewport:{width:1440,height:960},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto(pathToFileURL(path.join(root,'design/desktop.html')).href);
 await page.waitForFunction(()=>window.BoralancesPreview&&BoralancesPreview.surfaceCount()>2);
 await page.screenshot({path:path.join(root,'design/desktop-dark.png'),fullPage:true});
 await page.locator('#control-button').click();
 await page.locator('#light-mode').click();
 await page.locator('#close-control').click();
 await page.screenshot({path:path.join(root,'design/desktop-light.png'),fullPage:true});
 await page.locator('#overview-button').click();
 await page.locator('.mission').waitFor({state:'visible'});
 await page.locator('.mission [data-workspace="2"]').click();
 if(await page.locator('#space-name').innerText()!=='Time to play')throw Error('Workspace selector failed');
 await page.locator('#control-button').click();
 await page.locator('#reduce-motion').check();
 if(!await page.locator('body').evaluate(node=>node.classList.contains('reduced')))throw Error('Reduced motion failed');
 await page.locator('#glass-toggle').press('ArrowLeft');
 if(await page.locator('#glass-toggle').getAttribute('aria-checked')!=='false')throw Error('Reference switch keyboard control failed');
 await page.locator('#glass-toggle').press('ArrowRight');
 await page.screenshot({path:path.join(root,'design/control-center.png'),fullPage:true});
 await page.locator('#close-control').click();
 await page.locator('#launchpad').click();
 await page.locator('#app-search').fill('jarvis');
 if(await page.locator('.search-results button').count()!==1)throw Error('Application search failed');
 await page.keyboard.press('Escape');
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(out,'desktop-mobile.png'),fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Horizontal overflow');
 await page.setViewportSize({width:1440,height:960});
 await page.evaluate(()=>BoralancesPreview.screen('welcome'));
 await page.screenshot({path:path.join(root,'design/welcome.png'),fullPage:true});
 await page.evaluate(()=>BoralancesPreview.screen('boot'));
 await page.screenshot({path:path.join(root,'design/boot.png'),fullPage:true});
 await page.evaluate(()=>BoralancesPreview.screen('install'));
 for(let i=0;i<4;i++)await page.locator('#install-next').click();
 await page.screenshot({path:path.join(root,'design/installing.png'),fullPage:true});
 await page.locator('#install-next').click();
 if(!await page.locator('#install-title').innerText().then(x=>x.includes('Welcome home')))throw Error('Installer preview navigation failed');
 await page.goto(pathToFileURL(path.join(root,'design/brand-board.html')).href);
 await page.screenshot({path:path.join(root,'design/identity.png'),fullPage:true});
 await page.setViewportSize({width:1280,height:850});
 await page.goto(pathToFileURL(path.join(root,'apps/browser/boralances_browser/web/index.html')).href);
 await page.waitForFunction(()=>!!window.ReferenceGlass&&document.querySelectorAll('filter').length>0);
 await page.screenshot({path:path.join(out,'browser-home.png'),fullPage:true});
 await page.locator('#appearance').click();
 const report={desktopDark:true,desktopLight:true,workspaceSwitch:true,reducedMotion:true,referenceSwitchKeyboard:true,applicationSearch:true,setupScreens:true,identityBoard:true,mobileNoOverflow:true,browserReferenceOptics:true,pageErrors:errors};
 fs.writeFileSync(path.join(out,'visual-checks.json'),JSON.stringify(report,null,2));
 await browser.close();if(errors.length)throw Error(errors.join('\n'));console.log(JSON.stringify(report));
})().catch(error=>{console.error(error);process.exitCode=1;});
